export const createWorldBoundOriginalContactCalendarInitializer = (day: 10 | 11 = 11): OfficialPitchWorkloadCalendarInitializer =>
  ({ path, world, match, clubs, track }) => {
  const cycle = track(openSqliteWorldCompetitionCycleStore(path)), archive = track(openSqliteDomesticScheduleStore(path));
  cycle.initialize('career-a', worldCycleInput(0));
  const bound = initializeWorldBoundDomesticSeason({ cycle, world, archive, match }, {
    careerId: 'career-a', cycleOrdinal: 0, leagueRegion: 'ASIA_PACIFIC', seasonDayOne: '2032-02-19', clubs,
    standingsPolicy: { version: 'v1', tieCreditNumerator: 1, tieCreditDenominator: 2, runDifferentialCapPerGame: 10 },
    eventProfile: { version: 'events-v1', allStarEnabled: false, marketWindows: [], rosterExpansionEnabled: false, awardSelectionPolicyVersion: 'award-v1' },
    generatorInput: { seasonId: 'league-season-1', leagueId: 'league-a', calendarProfileVersion: 'calendar-v1', generatorVersion: 'generator-v1',
      scheduleSeed: 'seed-a', opponentMatrixVersion: 'matrix-v1', regularSeasonGamesPerClub: 4, memberClubIds: ['club-a', 'club-b'],
      opponentMatrix: [{ homeClubId: 'club-a', awayClubId: 'club-b', gameCount: 2 }, { homeClubId: 'club-b', awayClubId: 'club-a', gameCount: 2 }],
      allowedDays: Array.from({ length: 31 }, (_, i) => i + 10), reservedWindows: [], preferredSeriesLength: 2, minimumDaysBetweenRounds: 0 },
  });
  // The Core generates the first home series on days 10 and 11.
  // The default remains the existing February 29 V187 case.
  const game = bound.schedule.baseSchedule.games.find(item => item.day === day && item.homeClubId === 'club-a' && item.awayClubId === 'club-b');
  if (!game) throw new Error('formal home fixture was not generated by the Core');
  const fixture = registerDomesticFixtureFromWorld(world, archive, match, { careerId: 'career-a', seasonId: bound.schedule.seasonId, gameId: game.gameId }, game.day);
  const selections = track(openSqliteNationalCompetitionSelectionStore(path, { cycle })), careerCalendarEditionId = 'world-bound-original-v187-wbc';
  const careerCalendarSelection = selections.initialize({ careerId: 'career-a', editionId: careerCalendarEditionId, cycleOrdinal: 0,
    careerDayOne: '2031-01-01', cutoffDay: 300, kind: 'WBC' });
  return { game, seasonId: bound.schedule.seasonId, fixtureBinding: fixture.binding, calendarOrigin: bound.calendarOrigin,
    careerCalendarSelection, careerCalendarEditionId };
};

/** Fresh Native fixture only. Calendar/source declarations precede the actor;
 * the original authored bat placement is not normal AI anticipation/mastery. */
export const createWorldBoundOriginalContactV187 = (path: string) => {
  if (existsSync(path)) throw new Error('V187 requires a new database path; saved calendars cannot be backfilled');
  const x = originalBattingIntentFixture(path, createWorldBoundOriginalContactCalendarInitializer());
  try {
    const formal = x.f.calendarFixture;
    if (!formal) throw new Error('formal calendar was not initialized before the original actor');
    const source = x.withIntent('bunt'); x.actions.set(source.sourceId, source);
    const physical = x.pitches.accept(source.sourceId, 0), actor = physical.frame.batterActor;
    const contactEvent = physical.result.pitch.resolution.timeline.events.slice(physical.beforeTimeline.events.length)
      .find(item => item.kind === 'BatBallContact');
    if (!actor || !contactEvent || contactEvent.kind !== 'BatBallContact') throw new Error('formal original fixture lacks its actual actor/contact');
    const row = x.f.db.prepare('SELECT source_hash,snapshot_hash FROM main.physical_pitch_progress_actions WHERE source_id=?').get(source.sourceId)!;
    return { reference: { owner: 'physical_pitch_progress_actions' as const, sourceId: source.sourceId, sourceHash: String(row.source_hash), snapshotHash: String(row.snapshot_hash) },
      scope: { careerId: actor.binding.careerId, playerId: actor.binding.playerId },
      expectedPhysical: { source: physical.source, actor, contactEvent, contact: contactEvent.payload.contact, progressRevision: physical.progressRevision,
        scope: { careerId: physical.frame.workload.careerId, gameId: physical.frame.gameId, playId: physical.frame.match.playId, physicalPitchSourceId: source.sourceId } },
      expectedCalendar: { seasonDay: 11, calendarDateISO: '2032-02-29', careerDay: 425, careerDayOne: '2031-01-01' },
      calendarOrigin: formal.calendarOrigin, careerCalendarSelection: formal.careerCalendarSelection, careerCalendarEditionId: formal.careerCalendarEditionId,
      fixtureAuthority: { kind: 'EXPLICIT_NATIVE_FORMAL_CALENDAR_CONTACT_FIXTURE_V187', calendarSourceAuthoredBeforeActor: true,
        scheduleAndGameIdGeneratedByCore: true, batPlacement: 'EXISTING_AUTHORED_ORIGINAL_FIXTURE', normalAiProven: false, masteryProven: false, naturalCohortProven: false } };
  } finally { x.f.close(); }
};
