import { Vec3, vec3 } from '../math/vec3';
import { FIELD } from '../geometry/FieldConstants';

// ══════════════════════════════════════════════════════════════
// ★★★**リリース点は1つしかない**（にーくら恒久原則「見た目＝物理の一致」）
// ══════════════════════════════════════════════════════════════
//
// ここができるまで、リリース点は**4か所に書かれていた**:
//
//   `PitcherAI.executePitch`   … `vec3(±0.25, FIELD.GROUND_Y + 1.8, PITCH_DISTANCE − 1.8)`
//   `render/PitchMotion`       … `{ x: ±0.25, y: 1.8,               z: PITCH_DISTANCE − 1.8 }`
//   `render/PitchMotion` KEYS  … 同上（腕の通り道の終点として、もう一度）
//   `render/ReleaseRing`       … `group.position.set(±0.25, 1.8, PITCH_DISTANCE − 1.8)`
//
// **判定だけが `FIELD.GROUND_Y` を足していた**。地面は y=0.23 に宣言されている
// （にーくら「ここが地上だといったら、そこが地上だ」）ので、絵とリングは判定より
// **23cm 低い所**でボールを離していた。実際に何が起きていたか:
//
//   ・モーション中のボールは y=1.80 まで来る（＝リングの中心。ここで指を離す）
//   ・リリースした瞬間、飛行の第0点は y=2.03 → **ボールが 23cm 跳ね上がる**
//   ・「リングが重なる瞬間に離す」の"重なる"は、判定のリリース点ではない所で起きていた
//
// ★どちらへ寄せるかは迷う所ではない。`executePitch` に
// 「★リリース高は**地面からの高さ**。ゾーンと同じ土俵に乗せる」と書いてあり、
// 地面は宣言された値。**絵の側が地面を足し忘れていた**——だから絵を上げた。
// 物理は1ビットも動かない（較正・ゴールデン写しに影響しない）。
//
// ★★**これはリリース点であって、投手が立つ場所ではない**。立ち位置は
// `render/PlateCast.pitcherStandPos`（投手板のどこを踏むか）で、そこから
// 踏み出した先がここ。2つが離れすぎていないかは `render/pitchInvariants` が見る。

/**
 * **投手がどこでボールを離すか**。にーくらが投手チューナーで動かす値そのもので、
 * **絵も判定もここしか読まない**。
 *
 * ★★体の寸法ではなく**投げ方**の値。打者の `heightM` / `batLengthM` と同じで、
 * 絵から測った値を `PlayerRecord.release` に載せて判定へ渡す
 * （2026-08-05 に打者で決めた形——「同じ選手に体を2つ持たせない」）。
 */
export interface PitcherRelease {
  /** 投げる腕の側への横のずれ[m]。**右投手なら +x＝三塁側**（左投手は自動で反転する） */
  sideM: number;
  /**
   * **地面からの**リリース高さ[m]。★マウンドの高さ（10インチ）は**この中に含まれている**
   * ——実測のリリース高（MLB平均 約1.75m）も地面基準なので、`MOUND_HEIGHT` を足すと二重になる。
   */
  heightM: number;
  /** 投手板から本塁側へ踏み出す距離[m]（＝リリース点が投手板より何m手前か） */
  strideM: number;
}

// ══════════════════════════════════════════════════════════════
// ★★★**リリース高 1.8m → 1.4m**（にーくら 2026-08-09「うん。やってくれ」）
// ══════════════════════════════════════════════════════════════
// 1.8m は**この世界の縮尺から外れていた**。打者は身長1.5m、ストライクゾーンは
// 地面から 0.64〜1.03m。そこへ 1.8m から投げるのは、**打者より高い所**から球が出ている
// ということで、絵にすると投手だけ別の世界の住人になる。
//
// 1.4m の出どころ（実測 2026-08-09・`public/models/pawapro11.glb` を直に解いた）:
//   ・実際の野球の比（リリース高 ÷ ゾーン上端 ≒ 1.67）をこの世界へ当てると 1.7m 相当
//   ・打者との比（リリース高 ÷ 打者身長 ≒ 0.95）で当てると 1.4m 相当
//   ・パワプロくんの手は**身長の 70.3%** までしか上がらない（腕が短い）。
//     マウンド（地面＋10インチ）に立って地面から 1.4m へ手を届かせる身長は **1.63m**
//     ——打者1.5mの隣に立って違和感のない大きさ。1.8m を保つには身長 2.16m が要る。
// ★にーくらが選んだのは 1.4m。**高さは宣言するもの**（地面と同じ性格の数）なので、
// 私が実測から導き直さない。
//
// ★★これは**球の飛び方が変わる**変更（＝較正が動く）。低い所から出るぶん、
// 本塁までの落差が減って軌道が寝る。それが「見た目＝物理の一致」の値段。

/**
 * 既定値。**モデルが読めないときの保険**でもある。
 *
 * ★★実機では**リリース点は投手の手から測る**（`render/pitchHand.ts`）ので、ここは
 * 「その高さへ手が来るように投手の身長を決める」ための**目安**として効く。
 * ヘッドレス（私の環境）ではモデルが読めないので、常にここへ落ちる——
 * だから**私の測定値とにーくらの画面は一致しない**（`docs/測り方.md` と同じ罠）。
 */
export const DEFAULT_PITCHER_RELEASE: PitcherRelease = {
  sideM: 0.25,
  heightM: 1.4,
  strideM: 1.8,
};

/**
 * その投手のリリース点（ワールド座標）。**絵も判定もリングもこれを呼ぶ**。
 *
 * @param throws 利き腕。右投手のリリースは捕手から見て左＝三塁側(+x)
 * @param rel その投手の投げ方。省略＝既定
 */
export function releasePointFor(
  throws: 'R' | 'L',
  rel: PitcherRelease = DEFAULT_PITCHER_RELEASE
): Vec3 {
  return vec3(
    (throws === 'R' ? 1 : -1) * rel.sideM,
    // ★地面の上（`FIELD.GROUND_Y`）。ここを足し忘れたのが 23cm の破れの正体
    FIELD.GROUND_Y + rel.heightM,
    FIELD.PITCH_DISTANCE - rel.strideM
  );
}
