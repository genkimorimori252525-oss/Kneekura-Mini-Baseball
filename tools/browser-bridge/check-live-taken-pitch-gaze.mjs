import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {runInNewContext} from 'node:vm';
const context={};runInNewContext(await readFile('tools/browser-bridge/live-taken-pitch-gaze.js','utf8'),context);
const observe=context.KneekuraLiveTakenPitchGaze.observe,plain=v=>JSON.parse(JSON.stringify(v));
